"""The installer's feature lists and software catalogue rules.

Both installer front ends use these: the terminal installer
(cybexos-install) and the installer screen's service (cybexos-installerd).
They offer the same features and read the release's software catalogue
(desktop/software/catalogue.json, generated by scripts/software-catalogue)
under the same rules.

`flathub` is deliberately not a feature here: its module default governs it.
"""
from pathlib import Path
import re

from .common import Failure, read
from .software import ATTRIBUTE

# Every cybexos.features option an installation plan sets. Software profiles
# switch on their own (developer, steam); the assistant is always included.
FEATURES = ('developer', 'proprietary', 'steam', 'docker', 'podman', 'tailscale', 'connectedWidgets',
            'assistant', 'localNetworkServices')
# What the installers offer to choose individually: key, label, description.
SYSTEM_FEATURES = (
    ('docker', 'Docker', 'Container engine · its socket stays root-owned'),
    ('podman', 'Podman', 'Rootless containers and Distrobox'),
    ('tailscale', 'Tailscale', 'Mesh VPN'),
    ('localNetworkServices', 'Local network discovery', 'Avahi, .local names and LAN ports'),
    ('connectedWidgets', 'Calendar and online accounts', 'GNOME Calendar, online accounts and events in the clock'),
    ('proprietary', 'Proprietary applications', 'Chrome, 1Password, Claude Code, Steam and vendor apps'),
)
# Features whose software is itself unfree, off without proprietary applications.
UNFREE_FEATURES = ('steam',)

# App and profile ids; an id also names its icon file.
ID = re.compile(r'[a-z0-9][a-z0-9-]{0,63}')
# Nixpkgs attribute paths, as Software accepts them (cybexos.software.packages).
ATTRIBUTE_LIMIT = 200
UNUSABLE = 'Installation medium is missing its software catalogue. Nothing has been erased'


def valid_app(app):
    return (isinstance(app, dict) and isinstance(app.get('id'), str) and ID.fullmatch(app['id']) is not None
            and isinstance(app.get('attribute'), str) and len(app['attribute']) <= ATTRIBUTE_LIMIT
            and ATTRIBUTE.fullmatch(app['attribute']) is not None)


def valid_profile(profile):
    return (isinstance(profile, dict) and isinstance(profile.get('id'), str) and ID.fullmatch(profile['id']) is not None
            and isinstance(profile.get('apps', []), list) and all(isinstance(app, str) for app in profile.get('apps', []))
            and isinstance(profile.get('features', {}), dict))


def software_catalogue(directory, strict=True):
    """The catalogue in `directory`, with its apps and profiles checked.

    A missing or unreadable catalogue, or one without app and profile lists,
    always raises Failure. With `strict`, so does any app or profile that is
    not well formed: use it when a selection becomes an installation plan.
    Without it such entries are left out, for what a screen only displays.
    """
    try:
        data = read(Path(directory) / 'catalogue.json')
    except (Failure, OSError) as error:
        raise Failure(UNUSABLE) from error
    if not isinstance(data, dict) or not isinstance(data.get('apps'), list) or not isinstance(data.get('profiles'), list):
        raise Failure(UNUSABLE)
    apps = [app for app in data['apps'] if valid_app(app)]
    profiles = [profile for profile in data['profiles'] if valid_profile(profile)]
    if strict and (len(apps) != len(data['apps']) or len(profiles) != len(data['profiles'])):
        raise Failure(UNUSABLE)
    return {**data, 'apps': apps, 'profiles': profiles}
