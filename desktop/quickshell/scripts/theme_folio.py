"""System theme target: Folio, the file manager and Open and Save dialogs.

Renders folio/theme/colors.toml into the theme state directory, in the keys
of Omarchy's colors.toml that Folio reads (src/theme.cpp readPalette); the
Cybex OS package points it at the folio folder (nix/packages/folio.nix).
Folio derives its secondary text, tooltips and folder cards from these, and
`mode = "light"` tells it the palette is light.

Its plain text is the shell's muted text and its emphasis the shell's own
text, the step Omarchy's foreground and bright_foreground make. Folio draws
sizes and dates in a mix two thirds of the way from the background to the
plain text, so the plain text moves toward the shell's text just far enough
for that mix to read at 4.5:1. Its darker ground (text fields, the
preview's backdrop) is the background a step toward black. Kinds of file are
drawn in the terminal's blue (text), magenta (audio) and cyan (pictures),
already readable on this background.

Folio watches the file and restyles its open windows when it changes, so
there is nothing to signal.
"""
import theme_tokens

NAME = 'folio'
FILE = 'folio/theme/colors.toml'

HEADER = (
    '# Generated by theme-apply.py (scripts/theme_folio.py) from the shell\'s\n'
    '# appearance tokens. Rewritten whenever the appearance changes.\n'
)
# How far toward black the darker ground sits: further on a dark palette,
# where a small step does not show.
DARKER = {'dark': 0.3, 'light': 0.06}
# Folio's secondary text: mix(background, foreground, 0.68) (Theme::recomputeColors).
SECONDARY = 0.68
READABLE = 4.5
STEPS = 20


def plain_text(colors):
    """The muted text, or the least step toward the text that keeps Folio's
    secondary text readable."""
    background = colors['background']
    for step in range(STEPS + 1):
        candidate = theme_tokens.mix(colors['textMuted'], colors['text'], step / STEPS)
        if theme_tokens.contrast(theme_tokens.mix(background, candidate, SECONDARY), background) >= READABLE:
            return candidate
    return colors['text']


def palette(tokens):
    """(key, colour) pairs in file order."""
    colors = tokens['colors']
    ansi = theme_tokens.ansi_palette(tokens)
    return [
        ('accent', colors['accent']),
        ('background', colors['background']),
        ('dark_background', theme_tokens.mix(colors['background'], '#000000', DARKER[tokens['mode']])),
        ('lighter_background', colors['surfaceRaised']),
        ('foreground', plain_text(colors)),
        ('bright_foreground', colors['text']),
        ('red', colors['red']),
        ('yellow', colors['amber']),
        ('orange', colors['amber']),
        ('blue', ansi[4]),
        ('magenta', ansi[5]),
        ('cyan', ansi[6]),
    ]


def render(tokens):
    lines = [f'{key} = "{value}"' for key, value in palette(tokens)]
    if tokens['mode'] == 'light':
        lines.append('mode = "light"')
    return {FILE: HEADER + '\n'.join(lines) + '\n'}


